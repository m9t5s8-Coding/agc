struct RuntimeSignature {
  bool   returns_void = false;
  size_t argument_count = 0;
};

std::optional<RuntimeSignature>
runtime_signature(std::string_view name) {
  if (name == "__ag_alloc")
    return RuntimeSignature{false, 1};
  if (name == "__ag_write" || name == "__ag_read")
    return RuntimeSignature{false, 2};
  if (name == "__ag_free" || name == "__ag_exit")
    return RuntimeSignature{true, 1};
  return std::nullopt;
}

std::string
quote_llvm_name(std::string_view name) {
  std::string quoted = "@\"";
  for (const char character : name) {
    if (character == '\\' || character == '"')
      quoted.push_back('\\');
    quoted.push_back(character);
  }
  quoted.push_back('"');
  return quoted;
}

std::string
escape_llvm_bytes(const std::string& value) {
  std::string escaped;
  escaped.reserve(value.size() + 4);

  for (const unsigned char character : value) {
    if (character >= 32 && character <= 126 && character != '"' && character != '\\') {
      escaped.push_back(static_cast<char>(character));
    } else {
      escaped += std::format("\\{:02X}", static_cast<unsigned int>(character));
    }
  }

  // The existing DataItem lowering always emits a trailing NUL byte.
  escaped += "\\00";
  return escaped;
}

std::string
join(const std::vector<std::string>& values,
     std::string_view              separator) {
  std::string result;
  for (size_t i = 0; i < values.size(); ++i) {
    if (i != 0)
      result += separator;
    result += values[i];
  }
  return result;
}

class LLVMEmitter {
public:
  explicit LLVMEmitter(Parser& parser)
      : m_parser(parser) {}

  std::string
  run() {
    collect_globals();

    m_output << "; Generated by the AGC LLVM backend\n"
                "; Compile with: clang -x ir <this-file>.ll -o <program>\n"
                "target triple = \"x86_64-pc-linux-gnu\"\n"
                "\n";

    emit_globals();

    const auto& instructions = m_parser.get_instructions();
    for (size_t i = 0; i < instructions.size(); ++i) {
      auto* instruction = instructions[i].get();

      if (!m_pending_label.empty()) {
        emit_pending_label();
      }

      if (auto* data = dynamic_cast<DataItem*>(instruction)) {
        (void)data;
        continue;
      }

      if (auto* function = dynamic_cast<FunctionLabel*>(instruction)) {
        start_function(function);
        continue;
      }

      if (!m_function_open)
        continue;

      // Labels begin a new basic block, so handle them before ensure_block()
      // creates a synthetic dead block after a terminator.
      if (auto* label = dynamic_cast<Label*>(instruction)) {
        emit_label(label->m_name);
        continue;
      }

      ensure_block();

      if (auto* param = dynamic_cast<Param*>(instruction)) {
        emit_param(param);
      } else if (auto* assign = dynamic_cast<Assign*>(instruction)) {
        emit_assign(assign);
      } else if (auto* binary = dynamic_cast<Binary*>(instruction)) {
        emit_binary(binary);
      } else if (auto* index_assign = dynamic_cast<IndexAssign*>(instruction)) {
        emit_index_assign(index_assign);
      } else if (auto* member_load = dynamic_cast<MemberLoad*>(instruction)) {
        emit_member_load(member_load);
      } else if (auto* member_store = dynamic_cast<MemberStore*>(instruction)) {
        emit_member_store(member_store);
      } else if (auto* condition = dynamic_cast<CondJump*>(instruction)) {
        emit_cond_jump(condition, instructions, i);
      } else if (auto* jump = dynamic_cast<Jump*>(instruction)) {
        emit_jump(jump);
      } else if (auto* call = dynamic_cast<FunctionCall*>(instruction)) {
        emit_call(call);
      } else if (auto* return_instruction = dynamic_cast<Return*>(instruction)) {
        emit_return(return_instruction);
      }
    }

    finish_function();
    emit_declarations();
    emit_runtime();
    emit_main_wrapper();

    return m_output.str();
  }

private:
  struct CallInfo {
    bool   returns_void = false;
    size_t argument_count = 0;
  };

  void
  collect_globals() {
    for (const auto& instruction : m_parser.get_instructions()) {
      if (auto* data = dynamic_cast<DataItem*>(instruction.get())) {
        m_globals[data->m_name]       = data->m_value;
        m_global_sizes[data->m_name]  = data->m_value.size() + 1;
      } else if (auto* global = dynamic_cast<GlobalVariable*>(instruction.get())) {
        m_module_globals[global->m_name] = global->m_initializer;
      }
    }
  }

  std::string
  llvm_global_initializer(const std::string& initializer) {
    if (initializer.rfind("str.", 0) == 0)
      return "ptrtoint (ptr " + quote_llvm_name(initializer) + " to i64)";

    char*      end   = nullptr;
    const long long value = std::strtoll(initializer.c_str(), &end, 0);
    if (end != initializer.c_str() && *end == '\0')
      return std::to_string(value);

    if (initializer.size() > 2 && initializer[0] == '0' &&
        (initializer[1] == 'b' || initializer[1] == 'B')) {
      long long binary = 0;
      for (size_t i = 2; i < initializer.size(); ++i) {
        if (initializer[i] != '0' && initializer[i] != '1')
          return "0";
        binary = (binary << 1) | (initializer[i] == '1' ? 1 : 0);
      }
      return std::to_string(binary);
    }

    return "0";
  }

  void
  emit_globals() {
    for (const auto& [name, value] : m_globals) {
      const size_t size = m_global_sizes[name];
      m_output << quote_llvm_name(name) << " = private global ["
               << size << " x i8] c\"" << escape_llvm_bytes(value)
               << "\", align 1\n";
    }

    for (const auto& [name, initializer] : m_module_globals) {
      m_output << quote_llvm_name(name) << " = global i64 "
               << llvm_global_initializer(initializer) << ", align 8\n";
    }

    if (!m_globals.empty() || !m_module_globals.empty())
      m_output << '\n';
  }

  std::string
  new_temp() {
    return "%t" + std::to_string(m_temp++);
  }

  std::string
  new_dead_label() {
    return "dead." + std::to_string(m_dead_label++);
  }

  std::string
  new_cont_label() {
    return "cont." + std::to_string(m_cont_label++);
  }

  void
  ensure_block() {
    if (!m_block_terminated)
      return;

    m_output << new_dead_label() << ":\n";
    m_block_terminated = false;
  }

  void
  emit_pending_label() {
    m_output << m_pending_label << ":\n";
    m_pending_label.clear();
    m_block_terminated = false;
  }

  std::string
  slot_for(std::string_view name) {
    const std::string key(name);
    if (auto it = m_slots.find(key); it != m_slots.end())
      return it->second;

    if (auto variable = get_ir_table().lookup_data(m_function_index, name)) {
      if (auto slot = m_slots.find(variable->name); slot != m_slots.end())
        return slot->second;
    }
    if (auto variable = get_ir_table().lookup_source(m_function_index, name)) {
      if (auto slot = m_slots.find(variable->name); slot != m_slots.end())
        return slot->second;
    }

    // Destinations are normally declared in the IR table.  Keep a fallback so
    // malformed-but-parsed IR still produces a valid module.
    const std::string slot = "%slot" + std::to_string(m_slots.size());
    m_output << "  " << slot << " = alloca i64, align 8\n";
    m_output << "  store i64 0, ptr " << slot << ", align 8\n";
    m_slots[key] = slot;
    return slot;
  }

  std::string
  load_slot(const std::string& slot) {
    const std::string value = new_temp();
    m_output << "  " << value << " = load i64, ptr " << slot << ", align 8\n";
    return value;
  }

  void
  store_slot(const std::string& slot,
             const std::string& value) {
    m_output << "  store i64 " << value << ", ptr " << slot << ", align 8\n";
  }

  void
  store_destination(const std::string& destination,
                    const std::string& value) {
    if (auto global = get_ir_table().lookup_global_data(destination)) {
      m_output << "  store i64 " << value << ", ptr " << quote_llvm_name(global->name)
               << ", align 8\n";
      return;
    }
    if (auto global = get_ir_table().lookup_global_source(destination)) {
      m_output << "  store i64 " << value << ", ptr " << quote_llvm_name(global->name)
               << ", align 8\n";
      return;
    }
    store_slot(slot_for(destination), value);
  }

  std::string
  emit_value(std::string_view operand) {
    const std::string key(operand);

    if (auto it = m_slots.find(key); it != m_slots.end())
      return load_slot(it->second);

    if (auto variable = get_ir_table().lookup_data(m_function_index, operand)) {
      auto slot = m_slots.find(variable->name);
      if (slot != m_slots.end())
        return load_slot(slot->second);
    }

    if (auto variable = get_ir_table().lookup_source(m_function_index, operand)) {
      auto slot = m_slots.find(variable->name);
      if (slot != m_slots.end())
        return load_slot(slot->second);
    }

    if (auto global = get_ir_table().lookup_global_data(operand)) {
      const std::string value = new_temp();
      m_output << "  " << value << " = load i64, ptr " << quote_llvm_name(global->name)
               << ", align 8\n";
      return value;
    }

    if (auto global = get_ir_table().lookup_global_source(operand)) {
      const std::string value = new_temp();
      m_output << "  " << value << " = load i64, ptr " << quote_llvm_name(global->name)
               << ", align 8\n";
      return value;
    }

    if (auto global = m_globals.find(key); global != m_globals.end()) {
      const size_t size = m_global_sizes[key];
      const std::string address = new_temp();
      const std::string integer = new_temp();
      m_output << "  " << address << " = getelementptr inbounds ["
               << size << " x i8], ptr " << quote_llvm_name(key)
               << ", i64 0, i64 0\n";
      m_output << "  " << integer << " = ptrtoint ptr " << address << " to i64\n";
      return integer;
    }

    // Integer literals are the only remaining operands the current IR
    // produces.  Base 0 accepts decimal, hexadecimal, and octal spellings.
    char*      end      = nullptr;
    const long long value = std::strtoll(key.c_str(), &end, 0);
    if (end != key.c_str() && *end == '\0')
      return std::to_string(value);

    // Binary literals are lexed by AGC but are not understood by strtoll.
    if (key.size() > 2 && key[0] == '0' && (key[1] == 'b' || key[1] == 'B')) {
      long long binary = 0;
      for (size_t i = 2; i < key.size(); ++i) {
        if (key[i] != '0' && key[i] != '1')
          return "0";
        binary = (binary << 1) | (key[i] == '1' ? 1 : 0);
      }
      return std::to_string(binary);
    }

    return "0";
  }

  void
  start_function(FunctionLabel* function) {
    finish_function();

    m_function_index = function->function_index();
    m_function_label = function->m_name;
    m_function_open  = true;
    m_block_terminated = false;
    m_temp             = 0;
    m_params.clear();
    m_pending_label.clear();
    m_slots.clear();
    m_defined_functions.insert(m_function_label);

    auto entry = get_function_table().lookup(m_function_label);
    m_return_type = (entry && entry->return_type &&
                     entry->return_type->primitive_type == PrimitiveType::VOID)
                        ? "void"
                        : "i64";

    const size_t parameter_count = entry ? entry->parameters.size() : 0;
    std::vector<std::string> parameter_declarations;
    parameter_declarations.reserve(parameter_count);
    for (size_t i = 0; i < parameter_count; ++i)
      parameter_declarations.push_back("i64 %arg" + std::to_string(i));

    m_output << "define " << m_return_type << ' '
             << quote_llvm_name(m_function_label) << '('
             << join(parameter_declarations, ", ") << ") {\n"
             << "entry:\n";

    const auto* data = get_ir_table().lookup(m_function_index);
    if (!data)
      return;

    for (size_t i = 0; i < data->variables.size(); ++i) {
      const auto& variable = data->variables[i];
      const std::string slot = "%slot" + std::to_string(i);

      m_slots[variable->name] = slot;
      if (!variable->source_name.empty())
        m_slots[variable->source_name] = slot;

      m_output << "  " << slot << " = alloca i64, align 8\n";
      m_output << "  store i64 0, ptr " << slot << ", align 8\n";
    }

    // Spill incoming arguments into their stack slots, matching the native
    // backend's parameter model.
    for (const auto& variable : data->variables) {
      if (!variable->is_parameter || variable->param_index >= parameter_count)
        continue;

      auto slot = m_slots.find(variable->name);
      if (slot == m_slots.end())
        continue;

      m_output << "  store i64 %arg" << variable->param_index << ", ptr "
               << slot->second << ", align 8\n";
    }
  }

  void
  finish_function() {
    if (!m_function_open)
      return;

    if (!m_pending_label.empty())
      emit_pending_label();

    if (!m_block_terminated) {
      if (m_return_type == "void")
        m_output << "  ret void\n";
      else
        m_output << "  ret i64 0\n";
    }

    m_output << "}\n\n";
    m_function_open    = false;
    m_function_index   = -1;
    m_function_label.clear();
    m_block_terminated = true;
  }

  void
  emit_label(const std::string& name) {
    if (!m_block_terminated)
      m_output << "  br label %" << name << "\n";

    m_output << name << ":\n";
    m_block_terminated = false;
  }

  void
  emit_param(Param* param) {
    m_params.push_back(emit_value(param->m_name));
  }

  void
  emit_assign(Assign* assign) {
    const std::string value = emit_value(assign->m_source);
    store_destination(assign->m_destination, value);
  }

  void
  emit_binary(Binary* binary) {
    const std::string left  = emit_value(binary->m_left);
    const std::string right = emit_value(binary->m_right);
    const std::string result = new_temp();

    switch (binary->m_operator) {
    case BIN_OPERATOR::ADDITION:
      m_output << "  " << result << " = add i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::SUBTRACTION:
      m_output << "  " << result << " = sub i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::MULTIPLICATION:
      m_output << "  " << result << " = mul i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::DIVISION:
      m_output << "  " << result << " = sdiv i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::MODULUS:
      m_output << "  " << result << " = srem i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::BITWISE_AND:
    case BIN_OPERATOR::LOGICAL_AND:
      m_output << "  " << result << " = and i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::BITWISE_OR:
    case BIN_OPERATOR::LOGICAL_OR:
      m_output << "  " << result << " = or i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::BITWISE_XOR:
      m_output << "  " << result << " = xor i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::LEFT_SHIFT:
      m_output << "  " << result << " = shl i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::RIGHT_SHIFT:
      m_output << "  " << result << " = ashr i64 " << left << ", " << right << "\n";
      break;
    case BIN_OPERATOR::LESS_THAN:
    case BIN_OPERATOR::LESS_THAN_EQUAL:
    case BIN_OPERATOR::GREATER_THAN:
    case BIN_OPERATOR::GREATER_THAN_EQUAL:
    case BIN_OPERATOR::EQUAL_TO:
    case BIN_OPERATOR::NOT_EQUAL_TO: {
      const std::string comparison = new_temp();
      const char*       predicate  = "eq";
      switch (binary->m_operator) {
      case BIN_OPERATOR::LESS_THAN:
        predicate = "slt";
        break;
      case BIN_OPERATOR::LESS_THAN_EQUAL:
        predicate = "sle";
        break;
      case BIN_OPERATOR::GREATER_THAN:
        predicate = "sgt";
        break;
      case BIN_OPERATOR::GREATER_THAN_EQUAL:
        predicate = "sge";
        break;
      case BIN_OPERATOR::EQUAL_TO:
        predicate = "eq";
        break;
      case BIN_OPERATOR::NOT_EQUAL_TO:
        predicate = "ne";
        break;
      default:
        break;
      }
      m_output << "  " << comparison << " = icmp " << predicate << " i64 "
               << left << ", " << right << "\n";
      m_output << "  " << result << " = zext i1 " << comparison << " to i64\n";
      break;
    }
    case BIN_OPERATOR::INDEXING: {
      const std::string base    = new_temp();
      const std::string address = new_temp();
      const std::string byte    = new_temp();
      m_output << "  " << base << " = inttoptr i64 " << left << " to ptr\n";
      m_output << "  " << address << " = getelementptr i8, ptr " << base
               << ", i64 " << right << "\n";
      m_output << "  " << byte << " = load i8, ptr " << address << ", align 1\n";
      m_output << "  " << result << " = zext i8 " << byte << " to i64\n";
      break;
    }
    case BIN_OPERATOR::ASSIGN_TO:
    case BIN_OPERATOR::ARROW:
    case BIN_OPERATOR::NONE:
      m_output << "  " << result << " = add i64 " << left << ", 0\n";
      break;
    }

    store_destination(binary->m_store_to, result);
  }

  void
  emit_index_assign(IndexAssign* index_assign) {
    const std::string object = emit_value(index_assign->m_object);
    const std::string index  = emit_value(index_assign->m_index);
    const std::string value  = emit_value(index_assign->m_value);

    const std::string base    = new_temp();
    const std::string address = new_temp();
    const std::string byte    = new_temp();

    m_output << "  " << base << " = inttoptr i64 " << object << " to ptr\n";
    m_output << "  " << address << " = getelementptr i8, ptr " << base
             << ", i64 " << index << "\n";
    m_output << "  " << byte << " = trunc i64 " << value << " to i8\n";
    m_output << "  store i8 " << byte << ", ptr " << address << ", align 1\n";
  }

  void
  emit_member_load(MemberLoad* member_load) {
    const std::string object  = emit_value(member_load->m_object);
    const std::string base    = new_temp();
    const std::string address = new_temp();
    const std::string result  = new_temp();

    m_output << "  " << base << " = inttoptr i64 " << object << " to ptr\n";
    m_output << "  " << address << " = getelementptr i8, ptr " << base
             << ", i64 " << member_load->m_byte_offset << "\n";
    m_output << "  " << result << " = load i64, ptr " << address << ", align 8\n";
    store_destination(member_load->m_store_to, result);
  }

  void
  emit_member_store(MemberStore* member_store) {
    const std::string object  = emit_value(member_store->m_object);
    const std::string value   = emit_value(member_store->m_value);
    const std::string base    = new_temp();
    const std::string address = new_temp();

    m_output << "  " << base << " = inttoptr i64 " << object << " to ptr\n";
    m_output << "  " << address << " = getelementptr i8, ptr " << base
             << ", i64 " << member_store->m_byte_offset << "\n";
    m_output << "  store i64 " << value << ", ptr " << address << ", align 8\n";
  }

  void
  emit_cond_jump(CondJump*          condition,
                 const std::vector<AG_scope<Instructions>>& instructions,
                 size_t             position) {
    const std::string value      = emit_value(condition->m_cond);
    const std::string comparison = new_temp();

    std::string true_label;
    if (position + 1 < instructions.size()) {
      if (auto* next_label = dynamic_cast<Label*>(instructions[position + 1].get()))
        true_label = next_label->m_name;
    }

    if (true_label.empty()) {
      true_label     = new_cont_label();
      m_pending_label = true_label;
    }

    m_output << "  " << comparison << " = icmp ne i64 " << value << ", 0\n";
    m_output << "  br i1 " << comparison << ", label %" << true_label
             << ", label %" << condition->m_false_block << "\n";
    m_block_terminated = true;
  }

  void
  emit_jump(Jump* jump) {
    m_output << "  br label %" << jump->m_name << "\n";
    m_block_terminated = true;
  }

  void
  emit_call(FunctionCall* call) {
    const std::string label = call->m_name;

    bool function_returns_void = false;

    if (auto runtime = runtime_signature(label)) {
      function_returns_void = runtime->returns_void;
    } else {
      auto entry = get_function_table().lookup(label);
      function_returns_void = entry && entry->return_type &&
                              entry->return_type->primitive_type == PrimitiveType::VOID;
      m_calls[label] = CallInfo{function_returns_void, m_params.size()};
    }

    std::vector<std::string> arguments;
    arguments.reserve(m_params.size());
    for (const auto& parameter : m_params)
      arguments.push_back("i64 " + parameter);

    const std::string result_type = function_returns_void ? "void" : "i64";
    const std::string call_text
        = "  call " + result_type + " " + quote_llvm_name(label) + "("
          + join(arguments, ", ") + ")\n";

    if (!function_returns_void && !call->m_result.empty()) {
      const std::string result = new_temp();
      m_output << "  " << result << " = call " << result_type << ' '
               << quote_llvm_name(label) << "(" << join(arguments, ", ")
               << ")\n";
      store_destination(call->m_result, result);
    } else {
      m_output << call_text;
    }

    m_params.clear();
  }

  void
  emit_return(Return* return_instruction) {
    if (m_return_type == "void") {
      m_output << "  ret void\n";
    } else if (return_instruction->m_name.empty()) {
      m_output << "  ret i64 0\n";
    } else {
      const std::string value = emit_value(return_instruction->m_name);
      m_output << "  ret i64 " << value << "\n";
    }

    m_block_terminated = true;
  }

  void
  emit_declarations() {
    bool emitted = false;
    for (const auto& [label, info] : m_calls) {
      if (m_defined_functions.contains(label) || runtime_signature(label))
        continue;

      std::vector<std::string> parameters;
      parameters.reserve(info.argument_count);
      for (size_t i = 0; i < info.argument_count; ++i)
        parameters.push_back("i64");

      m_output << "declare " << (info.returns_void ? "void" : "i64") << ' '
               << quote_llvm_name(label) << '(' << join(parameters, ", ")
               << ")\n";
      emitted = true;
    }

    if (emitted)
      m_output << '\n';
  }

  void
  emit_runtime() {
    m_output << "declare ptr @calloc(i64, i64)\n"
                "declare void @free(ptr)\n"
                "declare i64 @write(i32, ptr, i64)\n"
                "declare i64 @read(i32, ptr, i64)\n"
                "declare void @exit(i32)\n"
                "\n"
                "define i64 @__ag_alloc(i64 %size) {\n"
                "entry:\n"
                "  %pointer = call ptr @calloc(i64 1, i64 %size)\n"
                "  %address = ptrtoint ptr %pointer to i64\n"
                "  ret i64 %address\n"
                "}\n"
                "\n"
                "define void @__ag_free(i64 %address) {\n"
                "entry:\n"
                "  %pointer = inttoptr i64 %address to ptr\n"
                "  call void @free(ptr %pointer)\n"
                "  ret void\n"
                "}\n"
                "\n"
                "define i64 @__ag_write(i64 %address, i64 %length) {\n"
                "entry:\n"
                "  %pointer = inttoptr i64 %address to ptr\n"
                "  %written = call i64 @write(i32 1, ptr %pointer, i64 %length)\n"
                "  ret i64 %written\n"
                "}\n"
                "\n"
                "define i64 @__ag_read(i64 %address, i64 %length) {\n"
                "entry:\n"
                "  %pointer = inttoptr i64 %address to ptr\n"
                "  %read_count = call i64 @read(i32 0, ptr %pointer, i64 %length)\n"
                "  ret i64 %read_count\n"
                "}\n"
                "\n"
                "define void @__ag_exit(i64 %code) {\n"
                "entry:\n"
                "  %status = trunc i64 %code to i32\n"
                "  call void @exit(i32 %status)\n"
                "  ret void\n"
                "}\n"
                "\n";
  }

  void
  emit_main_wrapper() {
    const auto* main_data = get_ir_table().find_function("main");
    if (!main_data || main_data->label.empty())
      return;

    auto entry = get_function_table().lookup(main_data->label);
    const bool main_returns_void = entry && entry->return_type &&
                                   entry->return_type->primitive_type == PrimitiveType::VOID;

    std::vector<std::string> arguments;
    const size_t parameter_count = entry ? entry->parameters.size() : 0;
    arguments.reserve(parameter_count);
    for (size_t i = 0; i < parameter_count; ++i)
      arguments.push_back("i64 0");

    m_output << "define i32 @main() {\n"
                "entry:\n";

    if (main_returns_void) {
      m_output << "  call void " << quote_llvm_name(main_data->label) << '('
               << join(arguments, ", ") << ")\n"
                  "  ret i32 0\n";
    } else {
      m_output << "  %result = call i64 " << quote_llvm_name(main_data->label)
               << '(' << join(arguments, ", ") << ")\n"
                  "  %status = trunc i64 %result to i32\n"
                  "  ret i32 %status\n";
    }

    m_output << "}\n";
  }

  Parser& m_parser;
  std::ostringstream m_output;

  std::map<std::string, std::string> m_globals;
  std::map<std::string, size_t>      m_global_sizes;
  std::map<std::string, std::string> m_module_globals;

  std::unordered_map<std::string, std::string> m_slots;
  std::unordered_set<std::string>              m_defined_functions;
  std::map<std::string, CallInfo>              m_calls;

  std::vector<std::string> m_params;
  std::string              m_pending_label;

  int         m_function_index = -1;
  std::string m_function_label;
  std::string m_return_type = "i64";

  bool m_function_open    = false;
  bool m_block_terminated = true;

  size_t m_temp       = 0;
  size_t m_dead_label = 0;
  size_t m_cont_label = 0;
};

